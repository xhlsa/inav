TEST(RxExpressLrsUnitTest, RcChannelsDecodeLikeUpstream)
{
    const int count = sizeof(elrsTestRcVectors) / sizeof(elrsTestRcVectors[0]);
    int checkedChannels = 0;

    for (int n = 0; n < count; n++) {
        const elrsTestRcVector_t *v = &elrsTestRcVectors[n];
        uint8_t payload[ELRS_RX_TX_BUFF_SIZE] = {0};
        uint16_t rcData[MAX_SUPPORTED_RC_CHANNEL_COUNT] = {0};

        initReceiverForTest(ELRS_TEST_BIND_PHRASE);
        ASSERT_EQ(RX_SPI_RECEIVED_LINK, feedPacket(v->sync, payload)) << "vector " << n;

        // Skip the phase lock handshake: this test covers the packet format
        receiver.connectionState = ELRS_CONNECTED;
        receiver.nonceRX = v->nonce;

        ASSERT_EQ(RX_SPI_RECEIVED_DATA, feedPacket(v->packet, payload)) << "vector " << n;

        expressLrsSetRcDataFromPayload(rcData, payload);
        for (int ch = 0; ch < 16; ch++) {
            if (v->expectedUs[ch]) {
                EXPECT_NEAR(v->expectedUs[ch], rcData[ch], 3) << "vector " << n << " channel " << ch;
                checkedChannels++;
            }
        }
    }

    // Every vector carries 4 sticks + AUX1, most also one round-robin switch
    EXPECT_GT(checkedChannels, count * 5);
}

TEST(RxExpressLrsUnitTest, ModelMatchMismatchNeverDeliversRc)
{
    initReceiverForTest(ELRS_TEST_BIND_PHRASE);
    rxExpressLrsSpiConfigMutable()->modelId = 7; // TX sends model match off
    uint8_t payload[ELRS_RX_TX_BUFF_SIZE] = {0};

    const elrsTestRcVector_t *v = &elrsTestRcVectors[0];
    ASSERT_EQ(RX_SPI_RECEIVED_LINK, feedPacket(v->sync, payload));
    receiver.connectionState = ELRS_CONNECTED;
    receiver.nonceRX = v->nonce;

    EXPECT_EQ(RX_SPI_RECEIVED_LINK, feedPacket(v->packet, payload));
}

TEST(RxExpressLrsUnitTest, LqCalc)
{
    lqReset();
    for (int i = 1; i <= 100; i++) {
        lqNewPeriod();
        lqIncrease();
        EXPECT_EQ(i, lqGet());
    }
    lqNewPeriod();
    lqIncrease();
    EXPECT_EQ(100, lqGet());
    for (int i = 99; i >= 0; i--) {
        lqNewPeriod();
        EXPECT_EQ(i, lqGet());
    }
}

