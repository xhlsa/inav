static void initReceiverForTest(const char *bindPhrase)
{
    memset(&receiver, 0, sizeof(receiver));
    memset(&runtimeConfig, 0, sizeof(runtimeConfig));
    runtimeConfig.lqTracker = &lqTracker;

    memset(rxExpressLrsSpiConfigMutable(), 0, sizeof(rxExpressLrsSpiConfig_t));
    strncpy(rxExpressLrsSpiConfigMutable()->bindPhrase, bindPhrase, EXPRESSLRS_BIND_PHRASE_MAX_LENGTH);
    rxExpressLrsSpiConfigMutable()->domain = ISM2400;
    rxExpressLrsSpiConfigMutable()->rateIndex = 3; // 250Hz
    rxExpressLrsSpiConfigMutable()->modelId = 0xFF;

    timerRunning = false;
    timerResumeCount = 0;
    saveCount = 0;
    DISABLE_ARMING_FLAG(ARMED);

    ASSERT_TRUE(expressLrsSpiInit(&rxConfigForTest, &runtimeConfig));
}

static rx_spi_received_e feedPacket(const uint8_t *packet, uint8_t *payload)
{
    memcpy((uint8_t *)expressLrsGetRxBuffer(), packet, ELRS_RX_TX_BUFF_SIZE);
    return processRFPacket(payload, 0);
}

