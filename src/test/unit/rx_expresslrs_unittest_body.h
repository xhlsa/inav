TEST(RxExpressLrsUnitTest, SyncPacketIsLinkNotRcData)
{
    initReceiverForTest(ELRS_TEST_BIND_PHRASE);
    uint8_t payload[ELRS_RX_TX_BUFF_SIZE] = {0};

    const elrsTestRcVector_t *v = &elrsTestRcVectors[0];
    EXPECT_EQ(RX_SPI_RECEIVED_LINK, feedPacket(v->sync, payload));

    EXPECT_EQ(ELRS_TENTATIVE, receiver.connectionState);
    EXPECT_EQ(ELRS_TEST_SYNC_NONCE, receiver.nonceRX);
    EXPECT_EQ(ELRS_TEST_SYNC_FHSS_INDEX, fhssGetCurrIndex());
    EXPECT_EQ(v->switchMode, receiver.switchMode);
    EXPECT_EQ(1, timerResumeCount);
}

TEST(RxExpressLrsUnitTest, RcPacketIgnoredUntilConnected)
{
    initReceiverForTest(ELRS_TEST_BIND_PHRASE);
    uint8_t payload[ELRS_RX_TX_BUFF_SIZE] = {0};

    const elrsTestRcVector_t *v = &elrsTestRcVectors[0];
    ASSERT_EQ(RX_SPI_RECEIVED_LINK, feedPacket(v->sync, payload));
    ASSERT_EQ(ELRS_TENTATIVE, receiver.connectionState);

    receiver.nonceRX = v->nonce;
    // Valid CRC, but not connected: must never be reported as RC data
    EXPECT_EQ(RX_SPI_RECEIVED_LINK, feedPacket(v->packet, payload));
}

TEST(RxExpressLrsUnitTest, CorruptPacketRejected)
{
    initReceiverForTest(ELRS_TEST_BIND_PHRASE);
    uint8_t payload[ELRS_RX_TX_BUFF_SIZE] = {0};

    uint8_t sync[8];
    memcpy(sync, elrsTestRcVectors[0].sync, sizeof(sync));
    sync[3] ^= 0x10;
    EXPECT_EQ(RX_SPI_RECEIVED_NONE, feedPacket(sync, payload));
    EXPECT_EQ(ELRS_DISCONNECTED, receiver.connectionState);
}

